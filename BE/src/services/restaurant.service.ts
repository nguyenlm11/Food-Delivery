import mongoose from "mongoose"
import { RestaurantParams } from "../interfaces/interface"
import Restaurant from "../models/restaurant.model"
import RestaurantCategory from "../models/restaurant_category.model"
import Category from "../models/category.model"
import Owner from "../models/owner.model"
import User from "../models/user.model"
import { generatePassword, generateRestaurantEmail, hashPassword } from "../utils/helper"
import { AppError } from "../errors/error"
import Role from "../models/role.model"
import { sendAccountToMail } from "../configs/email"

const handleCreateRestaurant = async (id: string, params: RestaurantParams) => {
    const { name, description, logoImage, coverImage, phone, address, location, openTime, closeTime, categoryIds } = params

    if (!mongoose.isValidObjectId(id)) {
        throw new AppError("Invalid ID format!", 400)
    }

    if (!categoryIds || !Array.isArray(categoryIds) || categoryIds.length === 0) {
        throw new AppError("At least one category is required", 400)
    }

    const [owner, validCategories, accountRole] = await Promise.all([
        Owner.findOne({ userId: id }).populate("userId"),
        Category.find({ _id: { $in: categoryIds }, isActive: true }),
        Role.findOne({ name: "RESTAURANT" })
    ])

    if (!owner) {
        throw new AppError("Owner account not found!", 404)
    }

    if (validCategories.length !== categoryIds.length) {
        throw new AppError("One or more categories are invalid or inactive", 400)
    }

    if (!accountRole) {
        throw new AppError("RESTAURANT role not found in system!", 500)
    }

    const autoGeneratedEmail = await generateRestaurantEmail(name)
    const autoGeneratedPassword = generatePassword()
    const hashPass = await hashPassword(autoGeneratedPassword)

    const session = await mongoose.startSession()
    let createdRestaurantId: mongoose.Types.ObjectId | null = null

    try {
        await session.withTransaction(async () => {
            const [restaurantAccount] = (await User.create([{
                fullname: name,
                email: autoGeneratedEmail,
                address: address,
                phone: phone,
                password: hashPass,
                status: "ACTIVE",
                roleId: accountRole._id
            }], { session }))

            const [newRestaurant] = (await Restaurant.create([{
                name: name,
                description: description,
                logoImage: logoImage,
                coverImage: coverImage,
                phone: phone,
                address: address,
                location: location,
                openTime: openTime,
                closeTime: closeTime,
                ownerId: owner._id,
                userId: restaurantAccount._id
            }], { session }))

            createdRestaurantId = newRestaurant._id

            const restaurantCategoryDocs = categoryIds.map((catId: string) => ({
                restaurantId: newRestaurant._id,
                categoryId: catId
            }))

            await RestaurantCategory.insertMany(restaurantCategoryDocs, { session })
        })
    } finally {
        await session.endSession()
    }

    try {
        await sendAccountToMail((owner.userId as any)?.email, autoGeneratedEmail, autoGeneratedPassword)
    } catch (emailError) {
        console.error("Failed to send restaurant account email:", emailError)
    }

    const result = await Restaurant
        .findById(createdRestaurantId)
        .populate({
            path: "userId",
            select: "-password -__v"
        })
        .lean()

    return result
}

export { handleCreateRestaurant }
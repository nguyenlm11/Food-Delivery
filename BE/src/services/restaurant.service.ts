import mongoose from "mongoose"
import { RestaurantParams, RestaurantSearchQuery } from "../interfaces/interface"
import Restaurant from "../models/restaurant.model"
import RestaurantCategory from "../models/restaurant_category.model"
import Category from "../models/category.model"
import Owner from "../models/owner.model"
import User from "../models/user.model"
import { generatePassword, generateRestaurantEmail, hashPassword } from "../utils/helper"
import { AppError } from "../errors/error"
import Role from "../models/role.model"
import { sendAccountToMail } from "../configs/email"

const handleCreateRestaurant = async (id: string, params: RestaurantParams) => {
    const { name, description, logoImage, coverImage, phone, address, longitude, latitude, openTime, closeTime, categoryIds } = params

    if (!mongoose.isValidObjectId(id)) {
        throw new AppError("Invalid ID format!", 400)
    }

    if (!categoryIds || !Array.isArray(categoryIds) || categoryIds.length === 0) {
        throw new AppError("At least one category is required", 400)
    }

    const [owner, validCategories, accountRole] = await Promise.all([
        Owner.findOne({ userId: id }).populate("userId"),
        Category.find({ _id: { $in: categoryIds }, isActive: true }),
        Role.findOne({ name: "RESTAURANT" })
    ])

    if (!owner) {
        throw new AppError("Owner account not found!", 404)
    }

    if (validCategories.length !== categoryIds.length) {
        throw new AppError("One or more categories are invalid or inactive", 400)
    }

    if (!accountRole) {
        throw new AppError("RESTAURANT role not found in system!", 500)
    }

    const autoGeneratedEmail = await generateRestaurantEmail(name)
    const autoGeneratedPassword = generatePassword()
    const hashPass = await hashPassword(autoGeneratedPassword)

    const session = await mongoose.startSession()
    let createdRestaurantId: mongoose.Types.ObjectId | null = null

    try {
        await session.withTransaction(async () => {
            const [restaurantAccount] = (await User.create([{
                fullname: name,
                email: autoGeneratedEmail,
                address: address,
                phone: phone,
                password: hashPass,
                status: "ACTIVE",
                roleId: accountRole._id
            }], { session }))

            const [newRestaurant] = (await Restaurant.create([{
                name: name,
                description: description,
                logoImage: logoImage,
                coverImage: coverImage,
                phone: phone,
                address: address,
                longitude: longitude,
                latitude: latitude,
                openTime: openTime,
                closeTime: closeTime,
                ownerId: owner._id,
                userId: restaurantAccount._id
            }], { session }))

            createdRestaurantId = newRestaurant._id

            const restaurantCategoryDocs = categoryIds.map((catId: string) => ({
                restaurantId: newRestaurant._id,
                categoryId: catId
            }))

            await RestaurantCategory.insertMany(restaurantCategoryDocs, { session })
        })
    } finally {
        await session.endSession()
    }

    try {
        await sendAccountToMail((owner.userId as any)?.email, autoGeneratedEmail, autoGeneratedPassword)
    } catch (emailError) {
        console.error("Failed to send restaurant account email:", emailError)
    }

    const result = await Restaurant
        .findById(createdRestaurantId)
        .populate({
            path: "userId",
            select: "-password -__v"
        })
        .lean()

    return result
}

const handleGetAllRestaurants = async (query: RestaurantSearchQuery) => {
    const search = query.search?.trim()
    const status = query.status
    const approvalStatus = query.approvalStatus
    const page = Math.max(1, Number(query.page) || 1)
    const limit = Math.max(1, Number(query.limit) || 10)
    const sortBy = query.sortBy || "createdAt"
    const sortOrder = query.sortOrder === "asc" ? 1 : -1

    const skip = (page - 1) * limit
    const mongoQuery: Record<string, any> = {}

    if (query.categoryIds) {
        const catIds = Array.isArray(query.categoryIds)
            ? query.categoryIds
            : query.categoryIds.split(",").map(id => id.trim()).filter(Boolean)

        if (catIds.length > 0) {
            const matchedRestaurantCategories = await RestaurantCategory
                .find({ categoryId: { $in: catIds } })
                .select("restaurantId")
                .lean()

            const matchedRestaurantIds = matchedRestaurantCategories.map(rc => rc.restaurantId)
            mongoQuery._id = { $in: matchedRestaurantIds }
        }
    }

    if (search) {
        mongoQuery.$or = [
            { name: { $regex: search, $options: "i" } },
            { phone: { $regex: search, $options: "i" } },
            { address: { $regex: search, $options: "i" } }
        ]
    }

    if (status) mongoQuery.status = status
    if (approvalStatus) mongoQuery.approvalStatus = approvalStatus

    const sort: Record<string, 1 | -1> = { [sortBy]: sortOrder }

    const [restaurants, total] = await Promise.all([
        Restaurant
            .find(mongoQuery)
            .select("name logoImage phone address status approvalStatus createdAt userId ownerId")
            .populate({ path: "userId", select: "fullname email phone status" })
            .populate({ path: "ownerId", select: "citizenId" })
            .sort(sort)
            .skip(skip)
            .limit(limit)
            .lean(),

        Restaurant.countDocuments(mongoQuery)
    ])

    if (restaurants.length === 0) {
        return {
            restaurants: [],
            pagination: { page, limit, total: 0, totalPages: 0 }
        }
    }

    const restaurantIds = restaurants.map(r => r._id)
    const restaurantCategories = await RestaurantCategory
        .find({ restaurantId: { $in: restaurantIds } })
        .populate({ path: "categoryId", select: "name slug iconImage" })
        .lean()

    const result = restaurants.map(restaurant => ({
        ...restaurant,
        categories: restaurantCategories
            .filter(item => item.restaurantId.toString() === restaurant._id.toString())
            .map(item => item.categoryId)
            .filter(Boolean)
    }))

    return {
        restaurants: result,
        pagination: {
            page,
            limit,
            total,
            totalPages: Math.ceil(total / limit)
        }
    }
}

const handleGetRestaurantById = async (id: string) => {
    if (!mongoose.isValidObjectId(id)) {
        throw new AppError("Invalid ID format!", 400)
    }

    const restaurant = await Restaurant
        .findById(id)
        .populate({ path: "userId", select: "fullname email phone status" })
        .populate({ path: "ownerId", select: "citizenId" })
        .lean()

    if (!restaurant) {
        throw new AppError("Restaurant not found!", 404)
    }

    const restaurantCategories = await RestaurantCategory
        .find({ restaurantId: restaurant._id })
        .populate({ path: "categoryId", select: "name slug iconImage" })
        .lean()

    const categories = restaurantCategories
        .map(item => item.categoryId)
        .filter(Boolean)

    return {
        ...restaurant,
        categories
    }
}

const handleDeleteRestaurant = async (id: string) => {
    if (!mongoose.isValidObjectId(id)) {
        throw new AppError("Invalid Restaurant ID format!", 400)
    }

    const restaurant = await Restaurant.findOneAndUpdate(
        { _id: id, status: { $ne: "INACTIVE" } },
        { $set: { status: "INACTIVE" } },
        { new: true }
    )

    if (!restaurant) {
        const existingRestaurant = await Restaurant.findById(id)
        if (!existingRestaurant) {
            throw new AppError("Restaurant not found!", 404)
        }

        throw new AppError("Restaurant is already inactive!", 400)
    }

    return {
        restaurantId: restaurant._id,
        status: restaurant.status
    }
}

const handleApproveRestaurant = async (id: string) => {
    if (!mongoose.isValidObjectId(id)) {
        throw new AppError("Invalid Restaurant ID format!", 400)
    }

    const restaurant = await Restaurant.findById(id)

    if (!restaurant) {
        throw new AppError("Restaurant not found!", 404)
    }

    if (restaurant.approvalStatus !== "PENDING") {
        throw new AppError(
            `Restaurant has already been ${restaurant.approvalStatus.toLowerCase()}!`,
            400
        )
    }

    restaurant.approvalStatus = "APPROVED"

    await restaurant.save()
}

const handleRejectRestaurant = async (id: string, rejectionReason: string) => {
    if (!mongoose.isValidObjectId(id)) {
        throw new AppError("Invalid Restaurant ID format!", 400)
    }

    const restaurant = await Restaurant.findById(id)

    if (!restaurant) {
        throw new AppError("Restaurant not found!", 404)
    }

    if (restaurant.approvalStatus !== "PENDING") {
        throw new AppError(
            `Restaurant has already been ${restaurant.approvalStatus.toLowerCase()}!`,
            400
        )
    }

    if (!rejectionReason || rejectionReason.trim() === "") {
        throw new AppError("Rejection reason is required!", 400)
    }

    restaurant.approvalStatus = "REJECTED"
    restaurant.rejectionReason = rejectionReason.trim()

    await restaurant.save()
}

const handleResubmitRestaurantApproval = async (id: string) => {
    if (!mongoose.isValidObjectId(id)) {
        throw new AppError("Invalid Restaurant ID format!", 400)
    }

    const restaurant = await Restaurant.findById(id)

    if (!restaurant) {
        throw new AppError("Restaurant not found!", 404)
    }

    if (restaurant.approvalStatus !== "REJECTED") {
        throw new AppError(`Restaurant has already been ${restaurant.approvalStatus.toLowerCase()}!`, 400)
    }

    restaurant.approvalStatus = "PENDING"
    restaurant.rejectionReason = ""

    await restaurant.save()
}

export { handleCreateRestaurant, handleGetAllRestaurants, handleGetRestaurantById, handleDeleteRestaurant, handleApproveRestaurant, handleRejectRestaurant, handleResubmitRestaurantApproval }
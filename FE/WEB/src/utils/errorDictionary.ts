const dynamicMessages: Array<[RegExp, (match: RegExpMatchArray) => string]> = [
    [
        /^Please wait (\d+) seconds before requesting a new OTP!$/,
        (match) => `Vui lòng đợi ${match[1]} giây trước khi yêu cầu mã OTP mới.`,
    ],
    [
        /^Food is already (available|unavailable)!$/,
        (match) => `Món ăn đã ${match[1] === "available" ? "được bật bán" : "được tạm ngừng bán"}.`,
    ],
    [
        /^Owner has already been (pending|approved|rejected)!$/,
        (match) => `Chủ nhà hàng đã ở trạng thái ${translateApprovalStatus(match[1])}.`,
    ],
    [
        /^Restaurant has already been (pending|approved|rejected)!$/,
        (match) => `Nhà hàng đã ở trạng thái ${translateApprovalStatus(match[1])}.`,
    ],
    [
        /^Restaurant is already (active|inactive|closed)!$/,
        (match) => `Nhà hàng đã ${translateRestaurantStatus(match[1])}.`,
    ],
    [
        /^Payment failed \(code ([^)]+)\)$/,
        (match) => `Thanh toán thất bại (mã ${match[1]}).`,
    ],
]

function translateApprovalStatus(status: string): string {
    const statuses: Record<string, string> = {
        pending: "chờ duyệt",
        approved: "được duyệt",
        rejected: "bị từ chối",
    }
    return statuses[status] ?? status
}

function translateRestaurantStatus(status: string): string {
    const statuses: Record<string, string> = {
        active: "hoạt động",
        inactive: "ngừng hoạt động",
        closed: "đóng cửa",
    }
    return statuses[status] ?? status
}

export function translateMessage(beMessage?: string): string {
    if (!beMessage) {
        return "Đã xảy ra lỗi. Vui lòng thử lại."
    }

    const translatedMessage = errorMap[beMessage]
    if (translatedMessage) {
        return translatedMessage
    }

    for (const [pattern, translate] of dynamicMessages) {
        const match = beMessage.match(pattern)
        if (match) {
            return translate(match)
        }
    }

    console.warn(`[errorDictionary] Chưa có bản dịch cho message từ Backend: "${beMessage}"`)
    return beMessage
}
